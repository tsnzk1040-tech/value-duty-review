/**
 * Shared prompt block for text members read (summary, 所感, 締め, 同テーマ引用).
 * Fixed templates set by toshio stay as they are; this only governs the free text.
 */
export function buildHumanVoiceBlock(
  part: "summary" | "leader" | "closing" | "quote",
): string {
  const common = [
    "【人が書いた文に見せる（AI生成の違和感を出さない）】",
    "- 上司がスマホで打つ長さと語彙にする。読み上げても不自然でない言い方。",
    "- 例文は分量と形の参考だけ。例の言い回し・書き出し・締めを写さない。",
    "- 投稿にある言葉をなるべくそのまま拾う。硬い漢語（実践する・推進・醸成・体現・意識向上・価値創出）へ置き換えない。",
    "- 決まり文句を使わない: まさに／素晴らしい／〜と言えるでしょう／〜ではないでしょうか／〜につながります／〜することで〜できます／大切なのは／ポイントは／改めて／ぜひ／〜のが伝わります／〜のが伝わってきます／〜の証拠ですね／〜のも良さそうです／〜につながった（のだと思います）。",
    "- 軽い動詞を使わない: 投げてみる／投げておく／投げて相談する／ぶつけてみる。",
    "- 投稿に書かれていない相手の気持ちや反応（嬉しかった・喜んだ・助かったはず・安心したと思う）を推測で書かない。書くのは投稿にある事実まで。",
    "- 「AだけでなくBも」「AとBとC」の三つ並べ・対句を型として入れない。投稿がそう書いているときだけ。",
    "- 投稿に無い程度・感情を盛らない（本当に・とても・しっかり・きちんと・深く・心から）。",
    "- 記号で整えない: ——、：、→、括弧の補足、箇条書き、見出し、太字、絵文字は使わない。",
    "- 体言止め・抽象名詞（〜という視点／学び／気づき／姿勢）で文を閉じるのを続けない。",
    "- 一文に情報を詰めない。読点で三つ以上つながったら、文を分ける。",
  ];
  const byPart: Record<typeof part, string[]> = {
    summary: [
      "- 前半の文を毎回同じ動詞で閉じない。投稿の行為ごとに変わってよい。",
    ],
    leader: [
      "- 共感の一文目は投稿の具体（場面・相手・言葉）から入る。「いいですね」「素敵ですね」「さすがですね」で毎回始めない。",
      "- 共感・テーマ・提案を同じ長さの三段にそろえない。短い文と少し長い文が混ざってよい。",
      "- 検索結果の主要な箇所を引くときの「」は使ってよい（括弧の補足とは別）。",
      "- 軽く聞こえる言い方を避ける: 〜でいいですね／素敵です／さすがです／面白いですね／ナイス／バッチリ。温かさは場面の受け止めで出す。",
      "- 一文目は投稿の事実だけで、40〜60字で一度切る。『〜した場面、』『〜した流れ、』『〜したところ、』のあとに感想を続ける形で作らない。『〜のですね』『〜んですね』で閉じない。事実をそのまま言い切るか、短い反応を添える。",
      "- 二文目を『〜ながらも／〜ものの／〜つつも／〜があったなかで』の譲歩で始めない。受け止めは『よかったです』『ほっとしました』程度の短い一言を、毎回違う語で入れてよい。",
      "- 『〜しつつも、〜した判断／対応が〜』の組み立てを使わない。",
      "- 上司自身の実感は入れない日があってよい。入れるときも『自分も同じ状況なら』『身につまされ』『情景が浮かび』『〜と思いながら読みました』のような決まった言い方にしない。",
      "- 落ち込みや失敗が強い投稿では、気持ちを言い足さない。投稿にある落ち込みの事実（手が止まった等）を一度だけそのまま受け止め、本人がしたことに移る。青ざめる・痛いほど・頭が下がります・苦い経験は使わない。事務的な『〜として受け止めました』にもしない。",
      "- 上司の評価に聞こえる言い方を使わない: 具体的で参考になります／〜が表れている／判断が〜につながった／姿勢ですね／〜の姿勢は／よく分かります／〜工夫を感じます／〜の助けになります／〜歩みですね。",
    ],
    closing: [
      "- 3案は書き出しと文の形をそれぞれ変える。3案とも「〜ですね」で閉じない。",
      "- 励ましの言葉で温度を出さない。投稿者の行為や場面を見ていると分かる一言で出す。評価口調（〜の証拠です／〜できていますね）にしない。",
      "- 「〜てみてください」「振り返ってみてください」は指示に聞こえる。3案目は問いの形で終える。1・2案目でも使うのは多くて1案。",
      "- 盛った言い方をしない: 〜そのものですね／ただの〜を超えて／〜の足がかりになります／〜が仕事の質を分けます／確かな一歩ですね。",
      "- 2案目を『〜がちですが』『〜たくなりますが』の逆接で毎回作らない。",
      "- 1案目を毎回『〜ですね』『〜でしたね』で閉じない。",
      "- 1案目に相手の受け取り方の推測（〜伝わったはずです）や評価（〜判断になったと感じます／〜のが伝わりました）を書かない。",
      "- 2案目を『〜たらと思います！』『〜でありたいと思います！』で毎回閉じない。「！」を付けない日があってよい。",
      "- 3案目は『直近／最近／いつ〜だったでしょう』の振り返りに限らず、次の場面を問う形も使う。",
    ],
    quote: [
      "- 前回要約の言葉をなるべく残す。整えすぎた言い換えにしない。",
    ],
  };
  return [...common, ...byPart[part]].join("\n");
}
